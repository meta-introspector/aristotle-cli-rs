#!/usr/bin/env python3
"""
Generate individual project webpages for each aristo project
"""

import html as html_escape
import json
from pathlib import Path

# Read the dedup report
with open('dedup-report.json') as f:
    report = json.load(f)

# Get the list of canonical projects
projects = []
for g in report['groups']:
    project_dir = g['canonical']
    status_file = Path(project_dir) / 'aristotle_status.json'
    if status_file.exists():
        with open(status_file) as f:
            status_data = json.load(f)
        created_at = status_data.get('created_at')
    else:
        created_at = None
    
    projects.append({
        'id': g['canonical'],
        'description': g['description'],
        'created_at': created_at,
        'archived_count': len(g['archived']),
        'status': status_data if status_file.exists() else {}
    })

# Sort projects by created_at (newest first) - fallback to description length
projects.sort(key=lambda p: (p['created_at'] or '', -len(p['description'])))

# HTML template for individual project page
HTML_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Aristotle Project - {project_id}</title>
<style>
* {{ box-sizing: border-box; }}
body {{
  font-family: system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
  background: #0f172a; color: #e2e8f0;
  max-width: 900px; margin: 0 auto; padding: 2rem 1.5rem;
}}
h1 {{ color: #38bdf8; margin-bottom: 0.25rem; }}
.subtitle {{ color: #94a3b8; margin-bottom: 1.5rem; }}
.section {{ margin-top: 2rem; }}
.section h2 {{ color: #94a3b8; font-size: 0.9rem; text-transform: uppercase; letter-spacing: 0.05em; margin-bottom: 0.75rem; }}
.card {{
  background: #1e293b; border: 1px solid #334155; border-radius: 0.75rem;
  padding: 1.5rem; margin: 1rem 0;
}}
.card h3 {{ margin: 0 0 1rem; color: #a5b4fc; font-size: 1.1rem; }}
.card pre {{ background: #0f172a; padding: 1rem; border-radius: 0.5rem; overflow: auto; max-height: 400px; }}
.meta {{ font-size: 0.85rem; color: #64748b; font-family: monospace; }}
.links {{ margin-top: 1rem; display: flex; gap: 1rem; flex-wrap: wrap; }}
.links a {{ color: #7dd3fc; text-decoration: none; }}
.links a:hover {{ text-decoration: underline; }}
.badge {{
  display: inline-block; font-size: 0.7rem; padding: 2px 8px;
  border-radius: 999px; background: #064e3b; color: #4ade80;
  margin: 2px; vertical-align: middle;
}}
.badge.archived {{ background: #1e3a5f; color: #93c5fd; }}
.back-link {{ display: inline-block; margin-bottom: 1.5rem; color: #7dd3fc; text-decoration: none; }}
.back-link:hover {{ text-decoration: underline; }}
.footer {{ color: #64748b; font-size: 0.8rem; margin-top: 3rem; border-top: 1px solid #334155; padding-top: 1.5rem; }}
code {{ background: #1e293b; padding: 1px 5px; border-radius: 3px; }}
</style>
</head>
<body>
<a href="/aristo/projects.html" class="back-link">← Back to Projects</a>
<h1>🏛️ Aristotle Project: {project_id}</h1>
<p class="subtitle">
  <span class="badge">Canonical</span>
  <span class="badge archived">{archived_count} archived variants</span>
  {has_files_badge}
  {has_input_badge}
</p>

<div class="section">
  <h2>Project Metadata</h2>
  <div class="card">
    <div class="meta">
      <strong>Created:</strong> {created_at}<br>
      <strong>Project ID:</strong> {project_id}<br>
      <strong>Status:</strong> {status_code}<br>
      <strong>Has Files:</strong> {has_files}<br>
      <strong>Has Input:</strong> {has_input}
    </div>
  </div>
</div>

<div class="section">
  <h2>Description</h2>
  <div class="card">
    <pre>{description}</pre>
  </div>
</div>

<div class="section">
  <h2>Links & Actions</h2>
  <div class="card">
    <div class="links">
      <a href="/aristo/api/{project_id}" target="_blank">📥 Download Result</a>
      <a href="/aristo/api/{project_id}/status" target="_blank">📊 Project Status</a>
      <a href="/aristo/api/{project_id}/files" target="_blank">📁 Files</a>
    </div>
  </div>
</div>

<div class="footer">
  <p>Generated by aristoprojects from dedup-report.json</p>
  <p>Deployment manifest: <code>deploy/manifests/project-{project_id}/</code></p>
</div>
</body>
</html>
"""

# Output directory
WWW_DIR = Path('www/projects')
WWW_DIR.mkdir(parents=True, exist_ok=True)

# Generate pages
for project in projects:
    pid = project['id']
    desc = project['description'][:5000]  # Truncate very long descriptions
    
    has_files = project['status'].get('has_files', False)
    has_input = project['status'].get('has_input', False)
    status_code = project['status'].get('status', 'Unknown')
    
    has_files_badge = '<span class="badge">Files ✓</span>' if has_files else '<span class="badge archived">No Files</span>'
    has_input_badge = '<span class="badge">Input ✓</span>' if has_input else '<span class="badge archived">No Input</span>'
    
    # Build the page using string replacement instead of format
    page = HTML_TEMPLATE
    page = page.replace('{project_id}', html_escape.escape(pid))
    page = page.replace('{created_at}', html_escape.escape(project['created_at'] or 'N/A'))
    page = page.replace('{archived_count}', html_escape.escape(str(project['archived_count'])))
    page = page.replace('{description}', html_escape.escape(desc))
    page = page.replace('{has_files_badge}', has_files_badge)
    page = page.replace('{has_input_badge}', has_input_badge)
    page = page.replace('{status_code}', html_escape.escape(str(status_code)))
    page = page.replace('{has_files}', str(has_files))
    page = page.replace('{has_input}', str(has_input))
    
    output_path = WWW_DIR / f"{pid}.html"
    with open(output_path, 'w') as f:
        f.write(page)

# Also generate an index page for all projects in the projects/ subdir
index_html = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Aristotle Projects - Individual Pages</title>
<style>
* { box-sizing: border-box; }
body {
  font-family: system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
  background: #0f172a; color: #e2e8f0;
  max-width: 1100px; margin: 0 auto; padding: 2rem 1.5rem;
}
h1 { color: #38bdf8; margin-bottom: 0.25rem; }
.subtitle { color: #94a3b8; margin-bottom: 1.5rem; }
.grid {
  display: grid;
  grid-template-columns: repeat(auto-fill, minmax(300px, 1fr));
  gap: 1rem;
}
.card {
  background: #1e293b; border: 1px solid #334155; border-radius: 0.75rem;
  padding: 1rem; display: flex; flex-direction: column; gap: 0.5rem;
  transition: transform 0.1s, border-color 0.1s;
}
.card:hover { transform: translateY(-2px); border-color: #6366f1; }
.card h3 { margin: 0; color: #a5b4fc; font-size: 0.95rem; word-break: break-all; }
.card .meta { font-size: 0.75rem; color: #64748b; font-family: monospace; }
.card .desc { font-size: 0.8rem; color: #cbd5e1; line-height: 1.4; }
.card .links { margin-top: auto; }
.card .links a { color: #7dd3fc; text-decoration: none; font-size: 0.8rem; margin-right: 0.75rem; }
.card .links a:hover { text-decoration: underline; }
.back-link { display: inline-block; margin-bottom: 1.5rem; color: #7dd3fc; text-decoration: none; }
.back-link:hover { text-decoration: underline; }
</style>
</head>
<body>
<a href="/aristo/projects.html" class="back-link">← Back to Main Projects</a>
<h1>🏛️ Aristotle Projects (Individual Pages)</h1>
<p class="subtitle">{count} canonical projects</p>
<div class="grid">
"""

for project in projects:
    pid = project['id']
    desc = project['description'][:300]
    created = project['created_at'] or 'N/A'
    archived = project['archived_count']
    
    index_html += f"""
  <div class="card">
    <h3>{html_escape.escape(pid)}</h3>
    <div class="meta">Created: {html_escape.escape(created)} | {html_escape.escape(str(archived))} archived</div>
    <div class="desc">{html_escape.escape(desc)}...</div>
    <div class="links">
      <a href="/aristo/projects/{pid}.html">View Details</a>
      <a href="/aristo/api/{pid}">Download</a>
    </div>
  </div>"""

index_html += """
</div>
</body>
</html>
"""

# Replace {count} placeholder
index_html = index_html.replace('{count}', str(len(projects)))

with open(WWW_DIR / "index.html", 'w') as f:
    f.write(index_html)

print(f"Generated {len(projects)} project pages in {WWW_DIR}")
print("Index page:", WWW_DIR / "index.html")